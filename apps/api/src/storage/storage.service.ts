import { GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import { Inject, Injectable } from '@nestjs/common';
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, posix, resolve, sep } from 'node:path';
import { APP_CONFIG, AppConfig } from '../config/app-config';

/**
 * Blob storage for recording chunks and finished recordings.
 * Swappable by env: local disk for dev/docker, any S3-compatible store (R2, S3, MinIO) in the cloud.
 */
export abstract class StorageService {
  abstract put(key: string, body: Buffer, contentType: string): Promise<void>;
  abstract get(key: string): Promise<Buffer>;
  /** A URL the browser can stream directly, or null when the API must serve the bytes itself. */
  abstract presignedGetUrl(key: string, ttlSeconds: number): Promise<string | null>;
  /** Absolute path on disk (local driver only), used to serve Range requests efficiently. */
  abstract localPath(key: string): Promise<string | null>;
}

/** Keys are generated by the server, but resolve defensively so a key can never escape the root. */
function safeJoin(root: string, key: string): string {
  const p = resolve(root, key);
  if (!p.startsWith(resolve(root) + sep)) throw new Error(`Invalid storage key: ${key}`);
  return p;
}

@Injectable()
export class LocalStorageService extends StorageService {
  private readonly root: string;

  constructor(@Inject(APP_CONFIG) cfg: AppConfig) {
    super();
    this.root = resolve(cfg.STORAGE_LOCAL_DIR);
  }

  async put(key: string, body: Buffer): Promise<void> {
    const p = safeJoin(this.root, key);
    await mkdir(dirname(p), { recursive: true });
    await writeFile(p, body);
  }

  get(key: string): Promise<Buffer> {
    return readFile(safeJoin(this.root, key));
  }

  async presignedGetUrl(): Promise<string | null> {
    return null;
  }

  async localPath(key: string): Promise<string | null> {
    const p = safeJoin(this.root, key);
    try {
      await stat(p);
      return p;
    } catch {
      return null;
    }
  }
}

@Injectable()
export class S3StorageService extends StorageService {
  private readonly s3: S3Client;
  private readonly bucket: string;

  constructor(@Inject(APP_CONFIG) cfg: AppConfig) {
    super();
    this.bucket = cfg.S3_BUCKET!;
    this.s3 = new S3Client({
      region: cfg.S3_REGION,
      endpoint: cfg.S3_ENDPOINT,
      forcePathStyle: !!cfg.S3_ENDPOINT, // R2 / MinIO
      credentials: { accessKeyId: cfg.S3_ACCESS_KEY_ID!, secretAccessKey: cfg.S3_SECRET_ACCESS_KEY! },
    });
  }

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    await this.s3.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: body, ContentType: contentType }));
  }

  async get(key: string): Promise<Buffer> {
    const res = await this.s3.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    return Buffer.from(await res.Body!.transformToByteArray());
  }

  presignedGetUrl(key: string, ttlSeconds: number): Promise<string | null> {
    return getSignedUrl(this.s3, new GetObjectCommand({ Bucket: this.bucket, Key: key }), { expiresIn: ttlSeconds });
  }

  async localPath(): Promise<string | null> {
    return null;
  }
}

export const storageKeys = {
  chunk: (callId: string, segment: number, seq: number) =>
    posix.join('calls', callId, 'chunks', String(segment).padStart(3, '0'), `${String(seq).padStart(6, '0')}.webm`),
  recording: (callId: string) => posix.join('calls', callId, 'recording.webm'),
};
